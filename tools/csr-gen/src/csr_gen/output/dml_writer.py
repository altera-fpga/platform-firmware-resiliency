"""Serialize CSR register models to Simics DML 1.4 device descriptions."""

from pathlib import Path
from textwrap import wrap

from csr_gen import __version__
from csr_gen.errors import CsrGenError
from csr_gen.model import (
    REGISTER_BYTES,
    Field,
    Register,
    RegisterModel,
    register_has_address_range,
    register_slot_count,
    validate_model,
)
from csr_gen.output.ascii_tables import (
    format_ascii_table,
    register_field_rows,
    register_map_rows,
)
from csr_gen.output.systemverilog_writer import module_name_from_section

_COMMENT_PREFIX = "// "
_WRAP_WIDTH = 78


class DmlGenerationError(CsrGenError):
    """Raised when DML generation cannot complete."""


def dml_name_from_section(section_heading: str) -> str:
    """Derive a DML device and bank identifier from a Markdown section heading."""
    return module_name_from_section(section_heading)


def write_dml_file(
    path: Path,
    model: RegisterModel,
    *,
    section_heading: str,
) -> None:
    """Write a Simics DML device description to a file."""
    path.write_text(write_dml(model, section_heading=section_heading), encoding="utf-8")


def write_dml(model: RegisterModel, *, section_heading: str) -> str:
    """Render a register model as a Simics DML 1.4 device."""
    heading = section_heading.strip()
    if not heading:
        raise DmlGenerationError(
            "A Markdown section heading is required to name the generated DML device."
        )
    validate_model(model)
    return _render_dml(model, heading)


def _render_dml(model: RegisterModel, section_heading: str) -> str:
    device_name = dml_name_from_section(section_heading)
    registers = _sorted_registers(model)
    lines: list[str] = [
        f"// Generated by csr-gen {__version__}. Do not edit by hand.",
        "",
        "dml 1.4;",
        "",
        f"device {device_name};",
        "",
        f'param desc = "{_escape_dml_string(section_heading)}";',
        f'param documentation = "{_escape_dml_string(section_heading)}";',
        "",
        'import "utility.dml";',
        "",
    ]
    lines.extend(_register_map_comment(registers))
    lines.extend(
        [
            "",
            f"bank {device_name} {{",
            f"    param register_size = {REGISTER_BYTES};",
            "",
        ]
    )
    for register in registers:
        lines.extend(_register_lines(register))
        lines.append("")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _register_map_comment(registers: list[Register]) -> list[str]:
    lines = ["// Register map"]
    lines.extend(
        format_ascii_table(
            ["Register", "Address", "Description"],
            register_map_rows(registers),
            line_prefix=_COMMENT_PREFIX,
        )
    )
    return lines


def _register_lines(register: Register) -> list[str]:
    if register_has_address_range(register):
        return _ranged_register_lines(register)
    return _fielded_register_lines(register)


def _ranged_register_lines(register: Register) -> list[str]:
    field = _sole_field(register)
    templates = _array_register_templates(field.access)
    slot_count = register_slot_count(register)
    description = _escape_dml_string(register.description or field.description)
    lines = [_register_header_comment(register)]
    lines.append(
        f"    register {register.name}[i < {slot_count}] "
        f"@ (0x{register.address:X} + i * {REGISTER_BYTES}) "
        f'is ({templates}) "{description}";'
    )
    return lines


def _fielded_register_lines(register: Register) -> list[str]:
    lines = [_register_header_comment(register)]
    lines.append(
        f"    register {register.name} size {REGISTER_BYTES} "
        f"@ 0x{register.address:X} {{"
    )
    if register.description:
        lines.extend(_comment_block(register.description, indent=8))
    for field in _sorted_fields(register):
        lines.extend(_field_lines(register, field))
    lines.append("    }")
    return lines


def _field_lines(register: Register, field: Field) -> list[str]:
    field_name = _field_dml_name(field.name)
    bit_range = _bit_range(field)
    templates = ", ".join(_field_templates(field.access))
    lines = [
        f"        field {field_name} @ {bit_range} is ({templates}) {{",
    ]
    if field.description:
        lines.extend(_comment_block(field.description, indent=12))
    lines.append(f"            param init_val = {_field_init_val(field)};")
    lines.append("        }")
    return lines


def _register_header_comment(register: Register) -> str:
    address = register.address
    if register_has_address_range(register):
        end = register.address_end
        header = f"    // --- {register.name} @ 0x{address:X}-0x{end:X} ---"
    else:
        header = f"    // --- {register.name} @ 0x{address:X} ---"
    return header


def _comment_block(text: str, *, indent: int) -> list[str]:
    prefix = " " * indent + _COMMENT_PREFIX
    lines: list[str] = []
    for paragraph in text.splitlines():
        paragraph = paragraph.strip()
        if not paragraph:
            continue
        wrapped = wrap(
            paragraph,
            width=_WRAP_WIDTH,
            break_long_words=False,
            break_on_hyphens=False,
        )
        lines.extend(f"{prefix}{line}" for line in wrapped)
    return lines


def _field_templates(access: str) -> list[str]:
    return {
        "none": ["reserved"],
        "ro": ["read_only"],
        "rc": ["clear_on_read"],
        "rw": ["read", "write"],
        "wo": ["write"],
        "rw1c": ["read", "write_1_clears"],
        "rw1s": ["read", "write_1_only"],
        "rw0c": ["read", "write_0_only"],
        "r0w1c": ["read_zero", "write_1_clears"],
    }[access]


def _array_register_templates(access: str) -> str:
    return {
        "rw": "read, write",
        "ro": "read_only",
        "wo": "write_only",
    }[access]


def _field_dml_name(name: str) -> str:
    parts = name.replace("-", "_").split("_")
    return "".join(part[:1].upper() + part[1:] for part in parts if part)


def _bit_range(field: Field) -> str:
    if field.msb == field.lsb:
        return f"[{field.msb}]"
    return f"[{field.msb}:{field.lsb}]"


def _field_init_val(field: Field) -> str:
    return f"0x{field.reset:X}"


def _escape_dml_string(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _sole_field(register: Register) -> Field:
    if len(register.fields) != 1:
        raise DmlGenerationError(
            f"Register {register.name!r} address range requires exactly one field."
        )
    return register.fields[0]


def _sorted_registers(model: RegisterModel) -> list[Register]:
    return sorted(model.registers, key=lambda register: register.address)


def _sorted_fields(register: Register) -> list[Field]:
    return sorted(register.fields, key=lambda field: field.msb, reverse=True)

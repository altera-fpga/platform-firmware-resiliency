"""Serialize CSR register models to C header files for firmware."""

from pathlib import Path

from csr_gen import __version__
from csr_gen.errors import CsrGenError
from csr_gen.model import Field, Register, RegisterModel, validate_model
from csr_gen.output.ascii_tables import (
    format_ascii_table,
    register_field_rows,
    register_map_rows,
)

_C_COMMENT_PREFIX = " * "


class CHeaderGenerationError(CsrGenError):
    """Raised when C header generation cannot complete."""


def macro_prefix_from_section(section_heading: str) -> str:
    """Derive a C macro prefix from a Markdown section heading."""
    return section_heading.strip().upper().replace(" ", "_")


def write_c_header_file(
    path: Path,
    model: RegisterModel,
    *,
    section_heading: str,
) -> None:
    """Write a C header describing the register block to a file."""
    path.write_text(
        write_c_header(model, section_heading=section_heading), encoding="utf-8"
    )


def write_c_header(model: RegisterModel, *, section_heading: str) -> str:
    """Render a register model as a C header."""
    heading = section_heading.strip()
    if not heading:
        raise CHeaderGenerationError(
            "A Markdown section heading is required to name the generated C header."
        )
    validate_model(model)
    return _render_c_header(model, macro_prefix_from_section(heading))


def _render_c_header(model: RegisterModel, macro_prefix: str) -> str:
    guard = f"{macro_prefix}_H"
    registers = _sorted_registers(model)
    lines: list[str] = [
        f"/* Generated by csr-gen {__version__}. Do not edit by hand. */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#ifndef __ASSEMBLY__",
        "#ifdef __cplusplus",
        "#include <cstdint>",
        'extern "C" {',
        "#else /* __cplusplus */",
        "#include <stdint.h>",
        "#endif /* __cplusplus */",
        "#endif /* __ASSEMBLY__ */",
        "",
    ]
    lines.extend(_usage_comment_block(macro_prefix, registers))
    lines.extend(
        [
            f"#ifndef {macro_prefix}_BASE_ADDR",
            f"#define {macro_prefix}_BASE_ADDR 0x{0:08X}u",
            "#endif",
            "",
        ]
    )
    for register in registers:
        lines.extend(_register_section(macro_prefix, register))
    lines.extend(
        [
            "#ifndef __ASSEMBLY__",
            "#ifdef __cplusplus",
            "}",
            "#endif /* __cplusplus */",
            "#endif /* __ASSEMBLY__ */",
            "",
            f"#endif /* {guard} */",
            "",
        ]
    )
    return "\n".join(lines)


def _usage_comment_block(macro_prefix: str, registers: list[Register]) -> list[str]:
    lines = [
        "/*",
        f" * {macro_prefix.replace('_', ' ').title()}",
        " *",
        " * Usage",
        " * -----",
        f" * 1. Optionally define {macro_prefix}_BASE_ADDR before including this",
        " *    header (default is 0).",
        " * 2. Provide platform reg_read() and reg_write() that transfer a full",
        " *    32-bit register value to/from a CPU address. This header does not",
        " *    define those functions.",
        " * 3. To change fields: read the register into a local uint32_t, apply the",
        " *    GET/SET macros below, then write the register back.",
        " *",
        " * Example:",
        f" *   uint32_t value = reg_read({macro_prefix}_CTRL_ADDR);",
        f" *   value = {macro_prefix}_CTRL_ENABLE_SET(value, 1);",
        f" *   reg_write({macro_prefix}_CTRL_ADDR, value);",
        " *",
        " * Access types in the tables (ro, wo, rw1c, etc.) describe hardware",
        " * behavior; the macros only manipulate a uint32_t in software.",
        " *",
        " * Register map",
        " * ------------",
    ]
    lines.extend(
        format_ascii_table(
            ["Register", "Address", "Description"],
            register_map_rows(registers),
            line_prefix=_C_COMMENT_PREFIX,
        )
    )
    lines.append(" */")
    lines.append("")
    return lines


def _register_section(macro_prefix: str, register: Register) -> list[str]:
    symbol = _register_symbol(macro_prefix, register)
    lines = [
        f"/* --- {register.name} @ 0x{register.address:02X} --- */",
        "/*",
    ]
    lines.extend(
        format_ascii_table(
            ["Field", "Bits", "Access", "Reset", "Description"],
            register_field_rows(register),
            line_prefix=_C_COMMENT_PREFIX,
        )
    )
    lines.append(" */")
    lines.append(f"#define {symbol}_OFFSET 0x{register.address:02X}u")
    lines.append(f"#define {symbol}_ADDR ({symbol}_OFFSET + {macro_prefix}_BASE_ADDR)")
    lines.append(f"#define {symbol}_RESET 0x{_register_reset_value(register):08X}u")
    exported = _sorted_exported_fields(register)
    if exported:
        lines.append("#ifndef __ASSEMBLY__")
        for field in exported:
            lines.extend(_field_defines(macro_prefix, register, field))
        lines.append("#endif /* __ASSEMBLY__ */")
    lines.append("")
    return lines


def _sorted_registers(model: RegisterModel) -> list[Register]:
    return sorted(model.registers, key=lambda register: register.address)


def _sorted_fields(register: Register) -> list[Field]:
    return sorted(register.fields, key=lambda field: field.lsb)


def _sorted_exported_fields(register: Register) -> list[Field]:
    return [field for field in _sorted_fields(register) if field.access != "none"]


def _register_symbol(macro_prefix: str, register: Register) -> str:
    return f"{macro_prefix}_{register.name}"


def _field_symbol(macro_prefix: str, register: Register, field: Field) -> str:
    return f"{_register_symbol(macro_prefix, register)}_{field.name}"


def _field_defines(macro_prefix: str, register: Register, field: Field) -> list[str]:
    symbol = _field_symbol(macro_prefix, register, field)
    mask = _field_mask(field)
    reset = _field_reset_value(field)
    return [
        f"#define {symbol}_MASK 0x{mask:08X}u",
        f"#define {symbol}_SHIFT {field.lsb}u",
        f"#define {symbol}_RESET 0x{reset:08X}u",
        f"#define {symbol}_GET(reg) \\",
        (f"    ((uint32_t)(((uint32_t)(reg) & {symbol}_MASK) >> " f"{symbol}_SHIFT))"),
        f"#define {symbol}_SET(reg, val) \\",
        (
            f"    ((uint32_t)(((uint32_t)(reg) & ~{symbol}_MASK) | "
            f"((((uint32_t)(val) << {symbol}_SHIFT) & {symbol}_MASK))))"
        ),
        "",
    ]


def _field_mask(field: Field) -> int:
    width = field.msb - field.lsb + 1
    return ((1 << width) - 1) << field.lsb


def _field_reset_value(field: Field) -> int:
    return (field.reset << field.lsb) & _field_mask(field)


def _register_reset_value(register: Register) -> int:
    value = 0
    for field in register.fields:
        width = field.msb - field.lsb + 1
        mask = (1 << width) - 1
        value |= (field.reset & mask) << field.lsb
    return value

"""Serialize CSR register models to SystemVerilog RTL."""

from pathlib import Path
from textwrap import indent

from csr_gen import __version__
from csr_gen.errors import CsrGenError
from csr_gen.model import (
    Field,
    Register,
    RegisterModel,
    register_address_end,
    register_decoder_addr_width,
    register_has_address_range,
    register_is_external,
    register_range_index_width,
    validate_model,
)
from csr_gen.output.ascii_tables import (
    format_ascii_table,
    register_field_rows,
    register_map_rows,
)

AXI4_LITE_INTERFACE = "axi4-lite"
UNSUPPORTED_INTERFACES = frozenset({"avalon-mm", "axi4", "apb"})

# Software-readable fields expose a module input driven by surrounding logic.
_SW_READABLE_ACCESSES = frozenset({"rw", "ro", "rc", "rw1c", "rw1s", "rw0c"})

# Software-writable fields expose a module output observed by surrounding logic.
_SW_WRITABLE_ACCESSES = frozenset({"rw", "wo", "rw1c", "rw1s", "rw0c", "r0w1c"})

_INDENT_SPACES = 4


def _indent(level: int) -> str:
    """Return indentation string for the given nesting level (4 spaces per level)."""
    return " " * (_INDENT_SPACES * level)


class RtlGenerationError(CsrGenError):
    """Raised when SystemVerilog generation cannot complete."""


def module_name_from_section(section_heading: str) -> str:
    """Derive a SystemVerilog module name from a Markdown section heading."""
    return section_heading.strip().lower().replace(" ", "_")


def write_systemverilog_file(
    path: Path,
    model: RegisterModel,
    interface_type: str,
    *,
    section_heading: str,
) -> None:
    """Write a SystemVerilog CSR block to a file."""
    path.write_text(
        write_systemverilog(model, interface_type, section_heading=section_heading),
        encoding="utf-8",
    )


def write_systemverilog(
    model: RegisterModel,
    interface_type: str,
    *,
    section_heading: str,
) -> str:
    """Render a register model as a SystemVerilog module."""
    normalized = interface_type.strip().lower()
    if normalized in UNSUPPORTED_INTERFACES:
        raise RtlGenerationError(
            f"SystemVerilog RTL generation for {interface_type} is not implemented yet."
        )
    if normalized != AXI4_LITE_INTERFACE:
        raise RtlGenerationError(
            f"Unsupported SystemVerilog interface type: {interface_type!r}."
        )
    heading = section_heading.strip()
    if not heading:
        raise RtlGenerationError(
            "A Markdown section heading is required to name the generated module."
        )
    validate_model(model)
    return _render_axi4lite(model, module_name_from_section(heading))


def _render_axi4lite(model: RegisterModel, module_name: str) -> str:
    offset_width = register_decoder_addr_width(model)
    registers = _sorted_registers(model)
    needs_ext_read_fsm = _model_needs_external_read_fsm(registers)
    port_lines = _module_port_lines(model, offset_width)
    lines: list[str] = [
        "`timescale 1 ps / 1 ps",
        "`default_nettype none",
        "",
        "// Generated by csr-gen " f"{__version__}. Do not edit by hand.",
        "",
        "// Register map",
        *format_ascii_table(
            ["Register", "Address", "Description"],
            register_map_rows(registers),
            line_prefix="// ",
        ),
        "",
        f"module {module_name} #(",
        f"{_indent(1)}parameter logic [31:0] BASE_ADDR = 32'h0000_0000",
        ") (",
        *port_lines,
        ");",
        "",
        f"{_indent(1)}localparam int unsigned OFFSET_WIDTH = {offset_width};",
        "",
        f"{_indent(1)}// AXI4-Lite interface",
        *_axi_signal_declarations(needs_ext_read_fsm, offset_width),
        *_axi_channel_logic(needs_ext_read_fsm, offset_width),
        "",
    ]
    for register in registers:
        if register_is_external(register):
            lines.extend(_external_register_section(register, offset_width))
        else:
            lines.extend(_internal_register_section(register, offset_width))
    lines.extend(_axi_pending_sequential(needs_ext_read_fsm, registers))
    lines.extend(_read_response_mux(registers, needs_ext_read_fsm))
    lines.extend(_response_logic(model))
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    return "\n".join(lines)


def _model_needs_external_read_fsm(registers: list[Register]) -> bool:
    return any(
        register_is_external(register) and _external_register_has_read_ports(register)
        for register in registers
    )


def _module_port_lines(model: RegisterModel, offset_width: int) -> list[str]:
    addr_port = f"[{offset_width - 1}:0]"
    ports = [
        f"{_indent(1)}input  wire        clk,",
        f"{_indent(1)}input  wire        rst,",
        f"{_indent(1)}// AXI4-Lite slave",
        f"{_indent(1)}input  wire {addr_port} s_axi_awaddr,",
        f"{_indent(1)}input  wire        s_axi_awvalid,",
        f"{_indent(1)}output logic        s_axi_awready,",
        f"{_indent(1)}input  wire [31:0] s_axi_wdata,",
        f"{_indent(1)}input  wire [ 3:0] s_axi_wstrb,",
        f"{_indent(1)}input  wire        s_axi_wvalid,",
        f"{_indent(1)}output logic        s_axi_wready,",
        f"{_indent(1)}output logic [ 1:0] s_axi_bresp,",
        f"{_indent(1)}output logic        s_axi_bvalid,",
        f"{_indent(1)}input  wire        s_axi_bready,",
        f"{_indent(1)}input  wire {addr_port} s_axi_araddr,",
        f"{_indent(1)}input  wire        s_axi_arvalid,",
        f"{_indent(1)}output logic        s_axi_arready,",
        f"{_indent(1)}output logic [31:0] s_axi_rdata,",
        f"{_indent(1)}output logic [ 1:0] s_axi_rresp,",
        f"{_indent(1)}output logic        s_axi_rvalid,",
        f"{_indent(1)}input  wire        s_axi_rready,",
        f"{_indent(1)}// Register interfaces",
    ]
    for register in _sorted_registers(model):
        ports.extend(_register_interface_port_lines(register))
    ports[-1] = ports[-1].rstrip(",")
    return ports


def _register_interface_port_lines(register: Register) -> list[str]:
    port_decls: list[str] = []
    if register_is_external(register):
        port_decls.extend(_external_register_port_declarations(register))
    else:
        for field in _sorted_fields(register):
            if _field_has_q_port(field):
                port_decls.append(
                    f"{_indent(1)}{_field_port_declaration(register, field, 'q')},"
                )
                port_decls.append(
                    f"{_indent(1)}{_field_valid_port_declaration(register, field, 'q_upd')},"
                )
            if _field_has_d_port(field):
                port_decls.append(
                    f"{_indent(1)}{_field_port_declaration(register, field, 'd')},"
                )
                port_decls.append(
                    f"{_indent(1)}{_field_valid_port_declaration(register, field, 'd_wen')},"
                )
    if not port_decls:
        return []
    return [_register_interface_port_comment(register), *port_decls]


def _register_address_comment_text(register: Register) -> str:
    if register_has_address_range(register):
        return f"0x{register.address:02X}-0x{register_address_end(register):02X}"
    return f"0x{register.address:02X}"


def _register_interface_port_comment(register: Register) -> str:
    return (
        f"{_indent(1)}// --- {register.name} @ "
        f"{_register_address_comment_text(register)} ---"
    )


def _external_register_port_declarations(register: Register) -> list[str]:
    prefix = _register_signal_prefix(register)
    lines: list[str] = []
    if _external_register_has_write_ports(register):
        lines.append(f"{_indent(1)}output logic        {prefix}_wren,")
        lines.append(f"{_indent(1)}output logic [31:0] {prefix}_wdata,")
        lines.append(f"{_indent(1)}output logic [ 3:0] {prefix}_wstrb,")
        if register_has_address_range(register):
            index_width = register_range_index_width(register)
            lines.append(
                f"{_indent(1)}output logic [{index_width - 1}:0] {prefix}_waddr,"
            )
    if _external_register_has_read_ports(register):
        lines.append(f"{_indent(1)}output logic        {prefix}_rden,")
        lines.append(f"{_indent(1)}input  wire [31:0] {prefix}_rdata,")
        lines.append(f"{_indent(1)}input  wire        {prefix}_rdatavalid,")
        if register_has_address_range(register):
            index_width = register_range_index_width(register)
            lines.append(
                f"{_indent(1)}output logic [{index_width - 1}:0] {prefix}_raddr,"
            )
    return lines


def _internal_register_section(register: Register, offset_width: int) -> list[str]:
    lines: list[str] = []
    lines.extend(_register_documentation(register))
    lines.extend(_register_address_localparams(register, offset_width))
    lines.extend(_register_constants(register))
    lines.append(f"{_indent(1)}logic [31:0] {_reg_signal(register)};")
    lines.append(f"{_indent(1)}logic {_hit_signal(register)};")
    lines.append(f"{_indent(1)}logic {_read_hit_signal(register)};")
    lines.append(f"{_indent(1)}logic [31:0] {_register_read_data_signal(register)};")
    lines.append(f"{_indent(1)}logic {_register_read_ok_signal(register)};")
    lines.append("")
    lines.extend(_register_address_decode(register))
    lines.extend(_register_field_q_assignments(register))
    lines.extend(_register_read_always_comb(register, immediate_read=True))
    lines.extend(_register_update_always_ff(register))
    lines.append("")
    return lines


def _external_register_section(register: Register, offset_width: int) -> list[str]:
    prefix = _register_signal_prefix(register)
    lines: list[str] = []
    lines.extend(_register_documentation(register))
    lines.extend(_register_address_localparams(register, offset_width))
    lines.append(f"{_indent(1)}logic {_hit_signal(register)};")
    lines.append(f"{_indent(1)}logic {_read_hit_signal(register)};")
    lines.append(f"{_indent(1)}logic [31:0] {_register_read_data_signal(register)};")
    lines.append(f"{_indent(1)}logic {_register_read_ok_signal(register)};")
    if _external_register_has_read_ports(register):
        lines.append(f"{_indent(1)}logic [31:0] {prefix}_ext_rdata_r;")
    if register_has_address_range(register) and _external_register_has_read_ports(
        register
    ):
        index_width = register_range_index_width(register)
        lines.append(f"{_indent(1)}logic [{index_width - 1}:0] {prefix}_slot_index;")
    lines.append("")
    lines.extend(_register_address_decode(register))
    lines.extend(_external_register_interface_logic(register))
    if _external_register_has_read_ports(register):
        lines.extend(_external_register_read_capture(register))
    lines.extend(
        _register_read_always_comb(
            register,
            immediate_read=not _external_register_has_read_ports(register),
        )
    )
    lines.append("")
    return lines


def _external_register_interface_logic(register: Register) -> list[str]:
    prefix = _register_signal_prefix(register)
    hit = _hit_signal(register)
    lines: list[str] = []

    if register_has_address_range(register) and _external_register_has_read_ports(
        register
    ):
        lines.append(
            f"{_indent(1)}assign {prefix}_slot_index = "
            f"{_range_slot_index_expr(register, 'read_offset')};"
        )
        lines.append("")

    if _external_register_has_write_ports(register):
        lines.append(f"{_indent(1)}assign {prefix}_wren = write_en && {hit};")
        lines.append(f"{_indent(1)}assign {prefix}_wdata = s_axi_wdata;")
        lines.append(f"{_indent(1)}assign {prefix}_wstrb = s_axi_wstrb;")
        if register_has_address_range(register):
            lines.append(
                f"{_indent(1)}assign {prefix}_waddr = "
                f"{_range_slot_index_expr(register, 'write_offset')};"
            )
        lines.append("")

    if _external_register_has_read_ports(register):
        lines.append(
            f"{_indent(1)}assign {prefix}_rden = "
            f"(s_axi_arvalid && s_axi_arready) && "
            f"{_read_hit_expr(register, 'ar_incoming_offset')};"
        )
        if register_has_address_range(register):
            lines.append(f"{_indent(1)}assign {prefix}_raddr = {prefix}_slot_index;")
        lines.append("")

    return lines


def _external_register_read_capture(register: Register) -> list[str]:
    prefix = _register_signal_prefix(register)
    return [
        f"{_indent(1)}always_ff @(posedge clk) begin",
        f"{_indent(2)}if (rst) begin",
        f"{_indent(3)}{prefix}_ext_rdata_r <= '0;",
        f"{_indent(2)}end else if ({prefix}_rdatavalid) begin",
        f"{_indent(3)}{prefix}_ext_rdata_r <= {prefix}_rdata;",
        f"{_indent(2)}end",
        f"{_indent(1)}end",
        "",
    ]


def _sv_comment_prefix() -> str:
    return f"{_indent(1)}// "


def _register_documentation(register: Register) -> list[str]:
    lines = [
        f"{_indent(1)}// --- {register.name} @ "
        f"{_register_address_comment_text(register)} ---"
    ]
    lines.extend(
        format_ascii_table(
            ["Field", "Bits", "Access", "Reset", "Description"],
            register_field_rows(register),
            line_prefix=_sv_comment_prefix(),
        )
    )
    lines.append("")
    return lines


def _read_hit_expr(register: Register, offset_expr: str) -> str:
    addr = _addr_localparam(register)
    if register_has_address_range(register):
        addr_end = _addr_end_localparam(register)
        return (
            f"(({offset_expr}[OFFSET_WIDTH-1:0] >= {addr}) && "
            f"({offset_expr}[OFFSET_WIDTH-1:0] <= {addr_end}))"
        )
    return f"({offset_expr}[OFFSET_WIDTH-1:0] == {addr})"


def _range_slot_index_expr(register: Register, offset_signal: str) -> str:
    index_width = register_range_index_width(register)
    base = _addr_localparam(register)
    return f"{index_width}'(" f"({offset_signal}[OFFSET_WIDTH-1:0] - {base}) >> 2" f")"


def _register_address_decode(register: Register) -> list[str]:
    return [
        f"{_indent(1)}assign {_hit_signal(register)} = "
        f"{_read_hit_expr(register, 'write_offset')};",
        f"{_indent(1)}assign {_read_hit_signal(register)} = "
        f"{_read_hit_expr(register, 'read_offset')};",
        "",
    ]


def _register_field_q_assignments(register: Register) -> list[str]:
    reg = _reg_signal(register)
    lines: list[str] = []
    for field in _sorted_fields(register):
        if not _field_has_q_port(field):
            continue
        port = _field_q_port(register, field)
        slice_range = f"{field.msb}:{field.lsb}"
        lines.append(f"{_indent(1)}assign {port} = {reg}[{slice_range}];")
    if lines:
        lines.append("")
    return lines


def _register_read_always_comb(
    register: Register, *, immediate_read: bool
) -> list[str]:
    read_data = _register_read_data_signal(register)
    read_ok = _register_read_ok_signal(register)
    hit = _read_hit_signal(register)
    prefix = _register_signal_prefix(register)
    lines = [
        f"{_indent(1)}always_comb begin",
        f"{_indent(2)}{read_data} = '0;",
        f"{_indent(2)}{read_ok} = 1'b0;",
        f"{_indent(2)}if ({hit}) begin",
    ]
    if register_is_external(register):
        if _external_register_has_read_ports(register):
            lines.append(f"{_indent(3)}if (read_resp_ready) begin")
            lines.append(f"{_indent(4)}{read_ok} = 1'b1;")
            lines.append(f"{_indent(4)}{read_data} = {prefix}_ext_rdata_r;")
            lines.append(f"{_indent(3)}end")
        else:
            lines.append(f"{_indent(3)}{read_ok} = 1'b1;")
            for field in _sorted_fields(register):
                expr = _field_read_expr(register, field, use_storage=False)
                lines.append(
                    f"{_indent(3)}{read_data}[{field.msb}:{field.lsb}] = {expr};"
                )
    else:
        if immediate_read:
            lines.append(f"{_indent(3)}{read_ok} = 1'b1;")
        else:
            lines.append(f"{_indent(3)}if (read_resp_ready) begin")
            lines.append(f"{_indent(4)}{read_ok} = 1'b1;")
        for field in _sorted_fields(register):
            expr = _field_read_expr_from_storage(register, field)
            indent_level = 3 if immediate_read else 4
            lines.append(
                f"{_indent(indent_level)}{read_data}[{field.msb}:{field.lsb}] = {expr};"
            )
        if not immediate_read:
            lines.append(f"{_indent(3)}end")
    lines.append(f"{_indent(2)}end")
    lines.append(f"{_indent(1)}end")
    lines.append("")
    return lines


def _register_update_always_ff(register: Register) -> list[str]:
    reg = _reg_signal(register)
    rst = _reg_rst_constant(register)
    write_hit = _hit_signal(register)
    read_hit = _read_hit_signal(register)
    q_fields = [field for field in _sorted_fields(register) if _field_has_q_port(field)]
    lines: list[str] = []
    for field in q_fields:
        lines.append(
            f"{_indent(1)}logic {_field_q_upd_pending_signal(register, field)};"
        )
    if q_fields:
        lines.append("")
    lines.append(f"{_indent(1)}always_ff @(posedge clk) begin")
    lines.append(f"{_indent(2)}if (rst) begin")
    lines.append(f"{_indent(3)}{reg} <= {rst};")
    for field in q_fields:
        q_upd = _field_q_upd_port(register, field)
        pending = _field_q_upd_pending_signal(register, field)
        lines.append(f"{_indent(3)}{q_upd} <= 1'b0;")
        lines.append(f"{_indent(3)}{pending} <= 1'b0;")
    lines.append(f"{_indent(2)}end else begin")
    for field in q_fields:
        q_upd = _field_q_upd_port(register, field)
        pending = _field_q_upd_pending_signal(register, field)
        lines.append(f"{_indent(3)}{q_upd} <= {pending};")
        lines.append(f"{_indent(3)}{pending} <= 1'b0;")
    lines.extend(
        indent(
            "\n".join(_internal_field_update_statements(register, write_hit)),
            _indent(3),
        ).splitlines()
    )
    read_clears = _register_read_clears(register)
    if read_clears:
        lines.append(f"{_indent(3)}if (read_en && {read_hit}) begin")
        lines.extend(
            indent(
                "\n".join(_internal_register_read_clear_statements(register)),
                _indent(4),
            ).splitlines()
        )
        lines.append(f"{_indent(3)}end")
    lines.append(f"{_indent(2)}end")
    lines.append(f"{_indent(1)}end")
    lines.append("")
    return lines


def _internal_field_update_statements(register: Register, write_hit: str) -> list[str]:
    reg = _reg_signal(register)
    lines: list[str] = []
    for field in _sorted_fields(register):
        if field.access == "none":
            continue
        slice_range = f"{field.msb}:{field.lsb}"
        reg_slice = f"{reg}[{slice_range}]"
        pending = _field_q_upd_pending_signal(register, field)
        mark_upd = f"{pending} <= 1'b1;"
        has_q_upd = _field_has_q_port(field)
        axi_update = _field_axi_write_update(field, reg)
        has_d = _field_has_d_port(field)

        if has_d:
            d_wen = _field_d_wen_port(register, field)
            d = _field_d_port(register, field)
            lines.append(f"if ({d_wen}) begin")
            lines.append(f"    {reg_slice} <= {d};")
            if has_q_upd:
                lines.append(f"    {mark_upd}")
            lines.append("end")
            if axi_update:
                lines.append(f"else if (write_en && {write_hit}) begin")
                lines.append(f"    {axi_update}")
                if has_q_upd:
                    lines.append(f"    {mark_upd}")
                lines.append("end")
        elif axi_update:
            lines.append(f"if (write_en && {write_hit}) begin")
            lines.append(f"    {axi_update}")
            if has_q_upd:
                lines.append(f"    {mark_upd}")
            lines.append("end")
    return lines


def _internal_register_read_clear_statements(register: Register) -> list[str]:
    """Emit rc clear updates that respect per-field _d_wen priority."""
    reg = _reg_signal(register)
    lines: list[str] = []
    for field in _sorted_fields(register):
        if field.access != "rc":
            continue
        slice_range = f"{field.msb}:{field.lsb}"
        reg_slice = f"{reg}[{slice_range}]"
        guard = _field_d_wen_port(register, field)
        lines.append(f"if (!{guard}) begin")
        lines.append(f"    {reg_slice} <= {_zero_literal(field.msb - field.lsb + 1)};")
        lines.append("end")
    return lines


def _axi_addr_logic_type(offset_width: int) -> str:
    return f"logic [{offset_width - 1}:0]"


def _zero_extend_to_32(expr: str, offset_width: int) -> str:
    """Zero-extend a narrow AXI address expression to 32 bits for BASE_ADDR math."""
    if offset_width >= 32:
        return expr
    pad = 32 - offset_width
    return f"{{{{{pad}{{1'b0}}}}, {expr}}}"


def _axi_signal_declarations(needs_ext_read_fsm: bool, offset_width: int) -> list[str]:
    addr_logic = _axi_addr_logic_type(offset_width)
    lines = [
        f"{_indent(1)}{addr_logic} s_axi_awaddr_r;",
        f"{_indent(1)}{addr_logic} s_axi_araddr_r;",
        f"{_indent(1)}logic        aw_pending;",
        f"{_indent(1)}logic        ar_pending;",
        f"{_indent(1)}logic        b_pending;",
        f"{_indent(1)}logic [31:0] write_offset;",
        f"{_indent(1)}logic [31:0] read_offset;",
        f"{_indent(1)}logic        write_en;",
        f"{_indent(1)}logic        read_en;",
        f"{_indent(1)}logic [31:0] read_data;",
        f"{_indent(1)}logic        write_ok;",
        f"{_indent(1)}logic        read_ok;",
    ]
    if needs_ext_read_fsm:
        lines.extend(
            [
                f"{_indent(1)}logic [31:0] ar_incoming_offset;",
                f"{_indent(1)}logic        read_resp_ready;",
                f"{_indent(1)}logic        ext_read_wait;",
            ]
        )
    lines.append("")
    return lines


def _axi_channel_logic(needs_ext_read_fsm: bool, offset_width: int) -> list[str]:
    rvalid_expr = (
        "ar_pending && read_resp_ready" if needs_ext_read_fsm else "ar_pending"
    )
    aw_ext = _zero_extend_to_32("s_axi_awaddr_r", offset_width)
    ar_ext = _zero_extend_to_32("s_axi_araddr_r", offset_width)
    ar_in_ext = _zero_extend_to_32("s_axi_araddr", offset_width)
    lines = [
        f"{_indent(1)}assign write_offset = {aw_ext} - BASE_ADDR;",
        f"{_indent(1)}assign read_offset = {ar_ext} - BASE_ADDR;",
    ]
    if needs_ext_read_fsm:
        lines.append(
            f"{_indent(1)}assign ar_incoming_offset = {ar_in_ext} - BASE_ADDR;"
        )
    lines.extend(
        [
            "",
            f"{_indent(1)}assign s_axi_awready = !aw_pending;",
            f"{_indent(1)}assign s_axi_wready = aw_pending;",
            f"{_indent(1)}assign write_en = aw_pending && s_axi_wvalid && s_axi_wready;",
            f"{_indent(1)}assign s_axi_bvalid = b_pending;",
            "",
            f"{_indent(1)}assign s_axi_arready = !ar_pending;",
            f"{_indent(1)}assign read_en = ar_pending && s_axi_rvalid && s_axi_rready;",
            f"{_indent(1)}assign s_axi_rvalid = {rvalid_expr};",
            f"{_indent(1)}assign s_axi_rdata = read_data;",
            "",
        ]
    )
    return lines


def _axi_pending_sequential(
    needs_ext_read_fsm: bool, registers: list[Register]
) -> list[str]:
    lines = [
        f"{_indent(1)}always_ff @(posedge clk) begin",
        f"{_indent(2)}if (rst) begin",
        f"{_indent(3)}aw_pending <= 1'b0;",
        f"{_indent(3)}b_pending <= 1'b0;",
        f"{_indent(3)}ar_pending <= 1'b0;",
    ]
    if needs_ext_read_fsm:
        lines.extend(
            [
                f"{_indent(3)}read_resp_ready <= 1'b0;",
                f"{_indent(3)}ext_read_wait <= 1'b0;",
            ]
        )
    lines.append(f"{_indent(2)}end else begin")
    lines.extend(
        [
            f"{_indent(3)}if (s_axi_awvalid && s_axi_awready) begin",
            f"{_indent(4)}aw_pending <= 1'b1;",
            f"{_indent(4)}s_axi_awaddr_r <= s_axi_awaddr;",
            f"{_indent(3)}end else if (write_en) begin",
            f"{_indent(4)}aw_pending <= 1'b0;",
            f"{_indent(3)}end",
            "",
            f"{_indent(3)}if (write_en) begin",
            f"{_indent(4)}b_pending <= 1'b1;",
            f"{_indent(3)}end else if (s_axi_bvalid && s_axi_bready) begin",
            f"{_indent(4)}b_pending <= 1'b0;",
            f"{_indent(3)}end",
            "",
        ]
    )
    if needs_ext_read_fsm:
        ext_valid_terms = _external_rdatavalid_hit_terms(registers)
        needs_wait_expr = _external_read_needs_wait_expr(registers)
        lines.extend(
            [
                f"{_indent(3)}if (s_axi_arvalid && s_axi_arready) begin",
                f"{_indent(4)}ar_pending <= 1'b1;",
                f"{_indent(4)}s_axi_araddr_r <= s_axi_araddr;",
                f"{_indent(4)}if ({needs_wait_expr}) begin",
                f"{_indent(5)}read_resp_ready <= 1'b0;",
                f"{_indent(5)}ext_read_wait <= 1'b1;",
                f"{_indent(4)}end else begin",
                f"{_indent(5)}read_resp_ready <= 1'b1;",
                f"{_indent(5)}ext_read_wait <= 1'b0;",
                f"{_indent(4)}end",
                f"{_indent(3)}end else if (read_en) begin",
                f"{_indent(4)}ar_pending <= 1'b0;",
                f"{_indent(4)}read_resp_ready <= 1'b0;",
                f"{_indent(4)}ext_read_wait <= 1'b0;",
                f"{_indent(3)}end else if (ext_read_wait && ({ext_valid_terms})) begin",
                f"{_indent(4)}read_resp_ready <= 1'b1;",
                f"{_indent(4)}ext_read_wait <= 1'b0;",
                f"{_indent(3)}end",
            ]
        )
    else:
        lines.extend(
            [
                f"{_indent(3)}if (s_axi_arvalid && s_axi_arready) begin",
                f"{_indent(4)}ar_pending <= 1'b1;",
                f"{_indent(4)}s_axi_araddr_r <= s_axi_araddr;",
                f"{_indent(3)}end else if (read_en) begin",
                f"{_indent(4)}ar_pending <= 1'b0;",
                f"{_indent(3)}end",
            ]
        )
    lines.extend([f"{_indent(2)}end", f"{_indent(1)}end", ""])
    return lines


def _external_read_needs_wait_expr(registers: list[Register]) -> str:
    terms = [
        _read_hit_expr(register, "ar_incoming_offset")
        for register in registers
        if register_is_external(register)
        and _external_register_has_read_ports(register)
    ]
    if not terms:
        return "1'b0"
    return " || ".join(terms)


def _external_rdatavalid_hit_terms(registers: list[Register]) -> str:
    terms = [
        f"({_read_hit_signal(register)} && "
        f"{_register_signal_prefix(register)}_rdatavalid)"
        for register in registers
        if register_is_external(register)
        and _external_register_has_read_ports(register)
    ]
    if not terms:
        return "1'b0"
    return " || ".join(terms)


def _read_response_mux(
    registers: list[Register], needs_ext_read_fsm: bool
) -> list[str]:
    lines = [
        f"{_indent(1)}// Read response mux",
        f"{_indent(1)}always_comb begin",
        f"{_indent(2)}read_data = '0;",
        f"{_indent(2)}read_ok = 1'b0;",
    ]
    for register in registers:
        read_ok = _register_read_ok_signal(register)
        read_data = _register_read_data_signal(register)
        guard = read_ok if not needs_ext_read_fsm else read_ok
        lines.append(f"{_indent(2)}if ({guard}) begin")
        lines.append(f"{_indent(3)}read_data = {read_data};")
        lines.append(f"{_indent(3)}read_ok = 1'b1;")
        lines.append(f"{_indent(2)}end")
    lines.append(f"{_indent(1)}end")
    lines.append("")
    return lines


def _response_logic(model: RegisterModel) -> list[str]:
    hit_terms = " || ".join(
        _hit_signal(register) for register in _sorted_registers(model)
    )
    if not hit_terms:
        hit_terms = "1'b0"
    return [
        f"{_indent(1)}// AXI response encoding",
        f"{_indent(1)}assign write_ok = {hit_terms};",
        f"{_indent(1)}assign s_axi_bresp = write_ok ? 2'b00 : 2'b10;",
        f"{_indent(1)}assign s_axi_rresp = read_ok ? 2'b00 : 2'b10;",
        "",
    ]


def _register_signal_prefix(register: Register) -> str:
    return register.name.lower()


def _field_signal_prefix(register: Register, field: Field) -> str:
    return f"{register.name.lower()}_{field.name.lower()}"


def _field_q_port(register: Register, field: Field) -> str:
    return f"{_field_signal_prefix(register, field)}_q"


def _field_d_port(register: Register, field: Field) -> str:
    return f"{_field_signal_prefix(register, field)}_d"


def _field_q_upd_port(register: Register, field: Field) -> str:
    return f"{_field_signal_prefix(register, field)}_q_upd"


def _field_d_wen_port(register: Register, field: Field) -> str:
    return f"{_field_signal_prefix(register, field)}_d_wen"


def _field_q_upd_pending_signal(register: Register, field: Field) -> str:
    return f"{_field_signal_prefix(register, field)}_q_upd_pend"


def _field_valid_port_declaration(register: Register, field: Field, kind: str) -> str:
    if kind == "q_upd":
        port = _field_q_upd_port(register, field)
        return f"output logic        {port}"
    port = _field_d_wen_port(register, field)
    return f"input  wire        {port}"


def _field_read_expr_from_storage(register: Register, field: Field) -> str:
    width = field.msb - field.lsb + 1
    access = field.access
    if access == "none":
        return _field_reset_literal(field)
    if access in {"wo", "r0w1c"}:
        return _zero_literal(width)
    reg = _reg_signal(register)
    return f"{reg}[{field.msb}:{field.lsb}]"


def _field_port_declaration(register: Register, field: Field, kind: str) -> str:
    port = (
        _field_q_port(register, field)
        if kind == "q"
        else _field_d_port(register, field)
    )
    keyword = "output logic" if kind == "q" else "input  wire"
    width = field.msb - field.lsb + 1
    if width == 1:
        return f"{keyword}        {port}"
    range_part = f"[{field.msb}:{field.lsb}]"
    return f"{keyword} {range_part} {port}"


def _sorted_registers(model: RegisterModel) -> list[Register]:
    return sorted(model.registers, key=lambda register: register.address)


def _sorted_fields(register: Register) -> list[Field]:
    return sorted(register.fields, key=lambda field: field.msb, reverse=True)


def _field_has_d_port(field: Field) -> bool:
    return field.access in _SW_READABLE_ACCESSES


def _field_has_q_port(field: Field) -> bool:
    return field.access in _SW_WRITABLE_ACCESSES


def _external_register_has_read_ports(register: Register) -> bool:
    return any(field.access in _SW_READABLE_ACCESSES for field in register.fields)


def _external_register_has_write_ports(register: Register) -> bool:
    return any(field.access in _SW_WRITABLE_ACCESSES for field in register.fields)


def _register_address_localparams(register: Register, offset_width: int) -> list[str]:
    lines = [
        _register_addr_localparam(register, offset_width),
    ]
    if register_has_address_range(register):
        lines.append(_register_addr_end_localparam(register, offset_width))
    return lines


def _register_addr_localparam(register: Register, offset_width: int) -> str:
    constant = _addr_localparam(register)
    offset = f"{offset_width}'h{register.address:X}"
    return f"{_indent(1)}localparam logic [OFFSET_WIDTH-1:0] {constant} = {offset};"


def _register_addr_end_localparam(register: Register, offset_width: int) -> str:
    constant = _addr_end_localparam(register)
    end = register_address_end(register)
    offset = f"{offset_width}'h{end:X}"
    return f"{_indent(1)}localparam logic [OFFSET_WIDTH-1:0] {constant} = {offset};"


def _register_constants(register: Register) -> list[str]:
    reset_value = _register_reset_value(register)
    constant = _reg_rst_constant(register)
    reset_literal = _hex32(reset_value)
    return [f"{_indent(1)}localparam logic [31:0] {constant} = {reset_literal};"]


def _register_read_clears(register: Register) -> list[str]:
    reg = _reg_signal(register)
    lines: list[str] = []
    for field in _sorted_fields(register):
        if field.access != "rc":
            continue
        width = field.msb - field.lsb + 1
        lines.append(f"{reg}[{field.msb}:{field.lsb}] <= {_zero_literal(width)};")
    return lines


def _field_axi_write_update(field: Field, reg: str) -> str | None:
    if field.access in {"none", "ro", "rc"}:
        return None
    slice_range = f"{field.msb}:{field.lsb}"
    wslice = f"s_axi_wdata[{slice_range}]"
    rslice = f"{reg}[{slice_range}]"
    strobe = _wstrb_covers_field(field)
    guard = f"if ({strobe})"
    access = field.access
    if access in {"rw", "wo"}:
        return f"{guard} {rslice} <= {wslice};"
    if access == "rw1c":
        return f"{guard} {rslice} <= {rslice} & ~{wslice};"
    if access == "rw1s":
        return f"{guard} {rslice} <= {rslice} | {wslice};"
    if access == "rw0c":
        return f"{guard} {rslice} <= {rslice} & {wslice};"
    if access == "r0w1c":
        return f"{guard} {rslice} <= {rslice} & ~{wslice};"
    return None


def _field_read_expr(register: Register, field: Field, *, use_storage: bool) -> str:
    slice_range = f"{field.msb}:{field.lsb}"
    width = field.msb - field.lsb + 1
    access = field.access
    if access == "none":
        return _field_reset_literal(field)
    if access in {"wo", "r0w1c"}:
        return _zero_literal(width)
    if _field_has_d_port(field):
        return _field_d_port(register, field)
    if use_storage:
        reg = _reg_signal(register)
        return f"{reg}[{slice_range}]"
    return _zero_literal(width)


def _field_reset_literal(field: Field) -> str:
    width = field.msb - field.lsb + 1
    return _hex_value(field.reset, width)


def _wstrb_covers_field(field: Field) -> str:
    low_byte = field.lsb // 8
    high_byte = field.msb // 8
    if low_byte == high_byte:
        return f"s_axi_wstrb[{low_byte}]"
    parts = [
        f"s_axi_wstrb[{byte_index}]" for byte_index in range(low_byte, high_byte + 1)
    ]
    return "(" + " || ".join(parts) + ")"


def _register_reset_value(register: Register) -> int:
    value = 0
    for field in register.fields:
        value |= (field.reset & ((1 << (field.msb - field.lsb + 1)) - 1)) << field.lsb
    return value


def _reg_signal(register: Register) -> str:
    return f"{register.name.lower()}_q"


def _reg_rst_constant(register: Register) -> str:
    return f"{register.name}_RST"


def _addr_localparam(register: Register) -> str:
    return f"{register.name}_ADDR"


def _addr_end_localparam(register: Register) -> str:
    return f"{register.name}_ADDR_END"


def _hit_signal(register: Register) -> str:
    return f"hit_{register.name.lower()}"


def _read_hit_signal(register: Register) -> str:
    return f"read_hit_{register.name.lower()}"


def _register_read_data_signal(register: Register) -> str:
    return f"{register.name.lower()}_read_data"


def _register_read_ok_signal(register: Register) -> str:
    return f"{register.name.lower()}_read_ok"


def _hex32(value: int) -> str:
    return f"32'h{value:08X}"


def _hex_value(value: int, width: int) -> str:
    return f"{width}'h{value:X}"


def _zero_literal(width: int) -> str:
    if width == 1:
        return "1'b0"
    return f"{width}'h0"

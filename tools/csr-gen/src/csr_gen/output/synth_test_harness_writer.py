"""Generate synthesizable SystemVerilog test harnesses for CSR blocks."""

from csr_gen.model import (
    Field,
    Register,
    RegisterModel,
    register_address_end,
    register_has_address_range,
    register_range_index_width,
)
from csr_gen.output.systemverilog_writer import (
    _external_register_has_read_ports,
    _external_register_has_write_ports,
    _field_d_wen_port,
    _field_d_port,
    _field_has_d_port,
    _field_has_q_port,
    _field_q_port,
    _field_q_upd_port,
    _register_interface_port_comment,
    _register_signal_prefix,
    _sorted_fields,
    _sorted_registers,
    module_name_from_section,
    register_is_external,
)

SYNTH_HARNESS_MODULE_NAME = "csr_synth_harness"
SYNTH_HARNESS_FILENAME = "csr_synth_harness.sv"

# AXI4-Lite slave ports (same directions as generated csr_registers).
_AXI_SLAVE_PORTS = [
    ("input  wire [31:0]", "s_axi_awaddr"),
    ("input  wire", "s_axi_awvalid"),
    ("output logic", "s_axi_awready"),
    ("input  wire [31:0]", "s_axi_wdata"),
    ("input  wire [ 3:0]", "s_axi_wstrb"),
    ("input  wire", "s_axi_wvalid"),
    ("output logic", "s_axi_wready"),
    ("output logic [ 1:0]", "s_axi_bresp"),
    ("output logic", "s_axi_bvalid"),
    ("input  wire", "s_axi_bready"),
    ("input  wire [31:0]", "s_axi_araddr"),
    ("input  wire", "s_axi_arvalid"),
    ("output logic", "s_axi_arready"),
    ("output logic [31:0]", "s_axi_rdata"),
    ("output logic [ 1:0]", "s_axi_rresp"),
    ("output logic", "s_axi_rvalid"),
    ("input  wire", "s_axi_rready"),
]


class SynthTestHarnessGenerationError(Exception):
    """Raised when a synthesizable test harness cannot be generated."""


def write_synth_test_harness_sv(model: RegisterModel, *, section_heading: str) -> str:
    """Render a synthesizable harness module that wraps the generated CSR block."""
    module_name = module_name_from_section(section_heading)
    d_ports = _collect_internal_d_ports(model)
    obs_ports = _collect_obs_ports(model)
    obs_width = sum(width for _port, width in obs_ports)
    lfsr_width = sum(width for _d, _en, width in d_ports) + len(d_ports) or 1

    lines: list[str] = [
        "// Generated by csr-gen synth_test_harness_writer. Check in; regenerate with:",
        "//   python scripts/generate_synth_test_harness.py <case-dir>",
        "`timescale 1 ps / 1 ps",
        "`default_nettype none",
        "",
        f"module {SYNTH_HARNESS_MODULE_NAME} (",
        "    // Clock and reset",
        "    input  wire        clk,",
        "    input  wire        rst,",
        "    // AXI4-Lite slave",
    ]
    for decl, name in _AXI_SLAVE_PORTS:
        lines.append(f"    {decl} {name},")
    lines.append("    // Harness observability")
    lines.append("    output logic       reg_obs")
    lines.append(");")
    lines.append("")
    lines.extend(_lfsr_block(lfsr_width))
    lines.extend(_register_interface_wire_lines(model))
    lines.extend(_field_stimulus_lines(d_ports, lfsr_width))
    lines.extend(_external_register_model_lines(model))
    lines.extend(_dut_instance(module_name, model))
    lines.extend(_observability_block(obs_ports, obs_width, lfsr_width=lfsr_width))
    lines.append("endmodule")
    lines.append("")
    return "\n".join(lines)


def _register_interface_wire_lines(model: RegisterModel) -> list[str]:
    """Declare internal wires for all CSR register interfaces (not module ports)."""
    lines: list[str] = []
    for register in _sorted_registers(model):
        if register_is_external(register):
            wire_lines = _external_register_wire_lines(register)
        else:
            wire_lines = _internal_register_wire_lines(register)
        if not wire_lines:
            continue
        lines.append(_register_interface_port_comment(register))
        lines.extend(wire_lines)
    if lines:
        lines.append("")
    return lines


def _internal_register_wire_lines(register: Register) -> list[str]:
    wire_lines: list[str] = []
    for field in _sorted_fields(register):
        if _field_has_q_port(field):
            wire_lines.append(_field_wire_declaration(register, field, "q"))
            wire_lines.append(f"    logic        {_field_q_upd_port(register, field)};")
        if _field_has_d_port(field):
            wire_lines.append(_field_wire_declaration(register, field, "d"))
            wire_lines.append(f"    logic        {_field_d_wen_port(register, field)};")
    return wire_lines


def _external_register_wire_lines(register: Register) -> list[str]:
    prefix = _register_signal_prefix(register)
    lines: list[str] = []
    if _external_register_has_write_ports(register):
        lines.append(f"    logic        {prefix}_wren;")
        lines.append(f"    logic [31:0] {prefix}_wdata;")
        lines.append(f"    logic [ 3:0] {prefix}_wstrb;")
        if register_has_address_range(register):
            index_width = register_range_index_width(register)
            lines.append(f"    logic [{index_width - 1}:0] {prefix}_waddr;")
    if _external_register_has_read_ports(register):
        lines.append(f"    logic        {prefix}_rden;")
        lines.append(f"    logic [31:0] {prefix}_rdata;")
        lines.append(f"    logic        {prefix}_rdatavalid;")
        if register_has_address_range(register):
            index_width = register_range_index_width(register)
            lines.append(f"    logic [{index_width - 1}:0] {prefix}_raddr;")
    return lines


def _field_wire_declaration(register: Register, field: Field, kind: str) -> str:
    port = (
        _field_q_port(register, field)
        if kind == "q"
        else _field_d_port(register, field)
    )
    width = field.msb - field.lsb + 1
    if width == 1:
        return f"    logic        {port};"
    range_part = f"[{field.msb}:{field.lsb}]"
    return f"    logic {range_part} {port};"


def _collect_internal_d_ports(
    model: RegisterModel,
) -> list[tuple[str, str, int]]:
    d_ports: list[tuple[str, str, int]] = []
    for register in _sorted_registers(model):
        if register_is_external(register):
            continue
        for field in _sorted_fields(register):
            if _field_has_d_port(field):
                d_port = _field_d_port(register, field)
                d_wen_port = _field_d_wen_port(register, field)
                width = field.msb - field.lsb + 1
                d_ports.append((d_port, d_wen_port, width))
    return d_ports


def _collect_obs_ports(model: RegisterModel) -> list[tuple[str, int]]:
    obs_ports: list[tuple[str, int]] = []
    for register in _sorted_registers(model):
        if register_is_external(register):
            continue
        for field in _sorted_fields(register):
            if _field_has_q_port(field):
                port = _field_q_port(register, field)
                width = field.msb - field.lsb + 1
                obs_ports.append((port, width))
    return obs_ports


def _register_storage_depth(register: Register) -> int:
    if register_has_address_range(register):
        return (register_address_end(register) - register.address + 1) // 4
    return 1


def _external_register_model_lines(model: RegisterModel) -> list[str]:
    lines: list[str] = []
    for register in _sorted_registers(model):
        if not register_is_external(register):
            continue
        lines.extend(_single_external_register_model(register))
    return lines


def _single_external_register_model(register: Register) -> list[str]:
    prefix = _register_signal_prefix(register)
    has_write = _external_register_has_write_ports(register)
    has_read = _external_register_has_read_ports(register)
    depth = _register_storage_depth(register)
    storage = f"{prefix}_storage"

    lines = [f"    // External model: {register.name}"]
    if depth == 1:
        lines.append(f"    logic [31:0] {storage};")
    else:
        lines.append(f"    logic [31:0] {storage} [0:{depth - 1}];")

    if has_read and has_write and depth == 1:
        lines.extend(
            [
                f"    logic        {prefix}_rdatavalid_r;",
                "    always_ff @(posedge clk) begin",
                "        if (rst) begin",
                f"            {storage} <= 32'h0;",
                f"            {prefix}_rdatavalid_r <= 1'b0;",
                "        end else begin",
                f"            {prefix}_rdatavalid_r <= {prefix}_rden;",
                f"            if ({prefix}_wren) begin",
                f"                {storage} <= {prefix}_wdata;",
                "            end",
                "        end",
                "    end",
                f"    assign {prefix}_rdata = {storage};",
                f"    assign {prefix}_rdatavalid = {prefix}_rdatavalid_r;",
                "",
            ]
        )
        return lines

    if has_write and has_read and depth > 1:
        lines.append(f"    logic        {prefix}_rdatavalid_r;")
        lines.extend(_storage_reset_block(storage, depth))
        lines.extend(
            [
                f"            {prefix}_rdatavalid_r <= 1'b0;",
                "        end else begin",
                f"            {prefix}_rdatavalid_r <= {prefix}_rden;",
                f"            if ({prefix}_wren) begin",
                f"                {storage}[{prefix}_waddr] <= {prefix}_wdata;",
                "            end",
                "        end",
                "    end",
                f"    assign {prefix}_rdata = {storage}[{prefix}_raddr];",
                f"    assign {prefix}_rdatavalid = {prefix}_rdatavalid_r;",
                "",
            ]
        )
        return lines

    if has_read and not has_write and depth > 1:
        init_values = [f"32'h{i + 1:08X}" for i in range(depth)]
        lines.append(f"    logic        {prefix}_rdatavalid_r;")
        lines.extend(_storage_reset_block(storage, depth, init_values=init_values))
        lines.extend(
            [
                f"            {prefix}_rdatavalid_r <= 1'b0;",
                "        end else begin",
                f"            {prefix}_rdatavalid_r <= {prefix}_rden;",
                "        end",
                "    end",
                f"    assign {prefix}_rdata = {storage}[{prefix}_raddr];",
                f"    assign {prefix}_rdatavalid = {prefix}_rdatavalid_r;",
                "",
            ]
        )
        return lines

    if has_write and not has_read and depth > 1:
        lines.extend(_storage_reset_block(storage, depth))
        lines.extend(
            [
                "        end else begin",
                f"            if ({prefix}_wren) begin",
                f"                {storage}[{prefix}_waddr] <= {prefix}_wdata;",
                "            end",
                "        end",
                "    end",
                "",
            ]
        )
        return lines

    raise SynthTestHarnessGenerationError(
        f"Unsupported external register model for {register.name!r}."
    )


def _storage_reset_block(
    storage: str,
    depth: int,
    *,
    init_values: list[str] | None = None,
) -> list[str]:
    lines = [
        "    always_ff @(posedge clk) begin",
        "        if (rst) begin",
    ]
    for index in range(depth):
        value = init_values[index] if init_values else "32'h0"
        lines.append(f"            {storage}[{index}] <= {value};")
    return lines


def _lfsr_block(width: int) -> list[str]:
    if width <= 1:
        return [
            "    logic [0:0] lfsr_q;",
            "",
            "    always_ff @(posedge clk) begin",
            "        if (rst) begin",
            "            lfsr_q <= 1'b1;",
            "        end else begin",
            "            lfsr_q <= lfsr_q ^ 1'b1;",
            "        end",
            "    end",
            "",
        ]
    hi = width - 1
    lo = width - 2
    return [
        f"    logic [{hi}:0] lfsr_q;",
        "",
        "    always_ff @(posedge clk) begin",
        "        if (rst) begin",
        f"            lfsr_q <= {width}'d1;",
        "        end else begin",
        f"            lfsr_q <= {{lfsr_q[{lo}:0],",
        f"                       lfsr_q[{hi}] ^ lfsr_q[{lo}] ^ 1'b1}};",
        "        end",
        "    end",
        "",
    ]


def _field_stimulus_lines(
    d_ports: list[tuple[str, str, int]], lfsr_width: int
) -> list[str]:
    if not d_ports:
        return []
    lines = ["    // LFSR-driven D inputs for internal hw_access register interfaces"]
    bit_offset = 0
    for d_port, d_wen_port, width in d_ports:
        if width == 1:
            lines.append(f"    assign {d_port} = lfsr_q[{bit_offset}];")
        else:
            hi = bit_offset + width - 1
            lines.append(f"    assign {d_port} = lfsr_q[{hi}:{bit_offset}];")
        bit_offset += width
    lines.append("")
    lines.append("    // Pulse _d_wen from LFSR bits above the D payload")
    d_wen_bit = bit_offset
    for _d_port, d_wen_port, _width in d_ports:
        if d_wen_bit >= lfsr_width:
            d_wen_bit = 0
        lines.append(f"    assign {d_wen_port} = lfsr_q[{d_wen_bit}];")
        d_wen_bit += 1
    lines.append("")
    return lines


def _dut_instance(module_name: str, model: RegisterModel) -> list[str]:
    from csr_gen.model import register_decoder_addr_width

    addr_width = register_decoder_addr_width(model)
    lines = [
        f"    {module_name} dut (",
        "        .clk(clk),",
        "        .rst(rst),",
    ]
    for _, name in _AXI_SLAVE_PORTS:
        if name in {"s_axi_awaddr", "s_axi_araddr"}:
            lines.append(f"        .{name}({name}[{addr_width - 1}:0]),")
        else:
            lines.append(f"        .{name}({name}),")
    for register in _sorted_registers(model):
        if register_is_external(register):
            lines.extend(_dut_external_connections(register))
        else:
            lines.extend(_dut_internal_connections(register))
    lines[-1] = lines[-1].rstrip(",")
    lines.append("    );")
    lines.append("")
    return lines


def _dut_internal_connections(register: Register) -> list[str]:
    lines: list[str] = []
    for field in _sorted_fields(register):
        if _field_has_q_port(field):
            q_port = _field_q_port(register, field)
            q_upd_port = _field_q_upd_port(register, field)
            lines.append(f"        .{q_port}({q_port}),")
            lines.append(f"        .{q_upd_port}({q_upd_port}),")
        if _field_has_d_port(field):
            d_port = _field_d_port(register, field)
            d_wen_port = _field_d_wen_port(register, field)
            lines.append(f"        .{d_port}({d_port}),")
            lines.append(f"        .{d_wen_port}({d_wen_port}),")
    return lines


def _dut_external_connections(register: Register) -> list[str]:
    prefix = _register_signal_prefix(register)
    lines: list[str] = []
    if _external_register_has_write_ports(register):
        for port in (f"{prefix}_wren", f"{prefix}_wdata", f"{prefix}_wstrb"):
            lines.append(f"        .{port}({port}),")
        if register_has_address_range(register):
            lines.append(f"        .{prefix}_waddr({prefix}_waddr),")
    if _external_register_has_read_ports(register):
        for port in (f"{prefix}_rden", f"{prefix}_rdata", f"{prefix}_rdatavalid"):
            lines.append(f"        .{port}({port}),")
        if register_has_address_range(register):
            lines.append(f"        .{prefix}_raddr({prefix}_raddr),")
    return lines


def _observability_block(
    obs_ports: list[tuple[str, int]], obs_width: int, *, lfsr_width: int
) -> list[str]:
    if obs_width == 0:
        if lfsr_width <= 0:
            return [
                "    assign reg_obs = 1'b0;",
                "",
            ]
        if lfsr_width == 1:
            return [
                "    // No internal hw_access Q outputs; observe LFSR activity",
                "    assign reg_obs = lfsr_q[0];",
                "",
            ]
        return [
            "    // No internal hw_access Q outputs; observe LFSR activity",
            "    assign reg_obs = ^lfsr_q;",
            "",
        ]
    if obs_width == 1:
        port, _width = obs_ports[0]
        return [
            f"    assign reg_obs = {port};",
            "",
        ]
    concat_expr = ", ".join(port for port, _width in obs_ports)
    return [
        "    // XOR internal hw_access register Q outputs for observability",
        f"    logic [{obs_width - 1}:0] reg_obs_vector;",
        f"    assign reg_obs_vector = {{{concat_expr}}};",
        "    assign reg_obs = ^reg_obs_vector;",
        "",
    ]

"""Serialize CSR register models to SystemRDL 2.0."""

from __future__ import annotations

from pathlib import Path

from csr_gen import __version__
from csr_gen.errors import CsrGenError
from csr_gen.model import (
    REGISTER_BYTES,
    Field,
    Register,
    RegisterModel,
    register_address_end,
    register_has_address_range,
    validate_model,
)
from csr_gen.output.register_order import sorted_fields, sorted_registers
from csr_gen.output.systemverilog_writer import module_name_from_section
from csr_gen.systemrdl.access import (
    ACCESS_UDP_NAME,
    field_access_properties,
    rdl_escape_string,
    rdl_identifier,
)


class SystemRdlGenerationError(CsrGenError):
    """Raised when SystemRDL generation cannot complete."""


_UDP_DECLARATIONS = f"""property {ACCESS_UDP_NAME} {{
    type = string;
    component = field;
}};
"""


def write_systemrdl_file(
    path: Path,
    model: RegisterModel,
    *,
    section_heading: str,
) -> None:
    """Write a SystemRDL addrmap describing the register block."""
    path.write_text(
        write_systemrdl(model, section_heading=section_heading),
        encoding="utf-8",
    )


def write_systemrdl(model: RegisterModel, *, section_heading: str) -> str:
    """Render a register model as a SystemRDL addrmap."""
    heading = section_heading.strip()
    if not heading:
        raise SystemRdlGenerationError(
            "A Markdown section heading is required to name the generated "
            "SystemRDL addrmap."
        )
    validate_model(model)
    addrmap_name = rdl_identifier(module_name_from_section(heading))
    lines: list[str] = [
        f"// Generated by csr-gen {__version__}. Do not edit by hand.",
        "",
        _UDP_DECLARATIONS.strip(),
        "",
        f"addrmap {addrmap_name} {{",
        f'    desc = "{rdl_escape_string(heading)}";',
        "",
    ]
    for register in sorted_registers(model):
        lines.extend(_render_register(register))
        lines.append("")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def _render_register(register: Register) -> list[str]:
    reg_name = rdl_identifier(register.name)
    prefix = (
        "external reg" if register.hw_access.strip().lower() == "external" else "reg"
    )
    lines = [f"    {prefix} {{"]
    lines.append("        regwidth = 32;")
    if register.description:
        lines.append(f'        desc = "{rdl_escape_string(register.description)}";')
    for register_field in sorted_fields(register):
        lines.extend(_render_field(register_field, indent="        "))
    lines.append(_register_instance_declaration(register, reg_name))
    return lines


def _register_instance_declaration(register: Register, reg_name: str) -> str:
    if register_has_address_range(register):
        count = _register_array_length(register)
        return f"    }} {reg_name}[{count}] @ {register.address:#x} += {REGISTER_BYTES:#x};"
    return f"    }} {reg_name} @ {register.address:#x};"


def _register_array_length(register: Register) -> int:
    from csr_gen.model import register_slot_count

    return register_slot_count(register)


def _render_field(field: Field, *, indent: str) -> list[str]:
    sw, onread, onwrite, hw = field_access_properties(field.access)
    field_name = rdl_identifier(field.name)
    properties = [
        f"sw = {sw};",
        f"hw = {hw};",
        f'{ACCESS_UDP_NAME} = "{rdl_escape_string(field.access)}";',
    ]
    if onread is not None:
        properties.append(f"onread = {onread};")
    if onwrite is not None:
        properties.append(f"onwrite = {onwrite};")
    if field.description:
        properties.append(f'desc = "{rdl_escape_string(field.description)}";')
    body = " ".join(properties)
    bit_range = f"{field.msb}:{field.lsb}"
    return [
        f"{indent}field {{ {body} }} {field_name}[{bit_range}] = {field.reset};",
    ]
